-- sortOrder 採番の同時実行競合対策（#166 ちゃっぴー監査対応）
-- 有効行（deleted = 0）の sortOrder に一意制約を付ける。
-- 列全体の UNIQUE ではなく部分インデックスにする理由:
--   論理削除済み行は現行仕様で sortOrder = 0 に揃えられるため、削除済み行が複数あると
--   列全体の一意制約では削除済み行同士が衝突してしまう。制約したいのは有効行の並び順だけなので、
--   WHERE deleted = 0 の部分インデックスで有効行だけを対象にする。
-- 0001 を書き換えず追加マイグレーションにする理由:
--   D1 のマイグレーションは名前で適用済みが管理され、適用済みファイルの書き換えは再実行されない。
--   本番 D1 にも同じ手順で流せるよう、変更は新しいマイグレーションとして積む。
-- 注意: 既存データに有効行の sortOrder 重複があるとこのインデックス作成は失敗する。
--   本実装のデータ移行時は、移行前に重複を解消してから流すこと（スパイクのシードは重複なし）。
CREATE UNIQUE INDEX idx_backgrounds_sort_order_active
  ON backgrounds (sortOrder)
  WHERE deleted = 0;
